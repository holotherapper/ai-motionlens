//! Tiny 5x7 bitmap font for burning labels into contact-sheet images.
//!
//! Only the glyphs needed for labels (`progress`, `t=`, `ms`, `scroll`, digits,
//! `.`, `=`, `:`, `%`, lowercase a-z, uppercase A-Z, spaces, `,`) are
//! supported. Unknown chars render as a small rectangle so missing-glyph cases
//! are obvious instead of silent.

use image::{Rgba, RgbaImage};

const CHAR_W: u32 = 5;
const CHAR_H: u32 = 7;

/// Draw `text` onto `img` at (`x`, `y`) using `scale` (each font pixel
/// becomes `scale`x`scale` image pixels). Color is RGBA.
pub fn draw_text(img: &mut RgbaImage, text: &str, x: i32, y: i32, scale: u32, color: [u8; 4]) {
    let mut cursor_x = x;
    for ch in text.chars() {
        if ch == ' ' {
            cursor_x += ((CHAR_W + 1) * scale) as i32;
            continue;
        }
        let glyph = glyph_for(ch);
        for row in 0..CHAR_H {
            for col in 0..CHAR_W {
                if glyph[row as usize] & (1 << (CHAR_W - 1 - col)) != 0 {
                    let px0 = cursor_x + (col * scale) as i32;
                    let py0 = y + (row * scale) as i32;
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = px0 + sx as i32;
                            let py = py0 + sy as i32;
                            if px >= 0
                                && py >= 0
                                && (px as u32) < img.width()
                                && (py as u32) < img.height()
                            {
                                img.put_pixel(px as u32, py as u32, Rgba(color));
                            }
                        }
                    }
                }
            }
        }
        cursor_x += ((CHAR_W + 1) * scale) as i32;
    }
}

pub fn measure_text(text: &str, scale: u32) -> (u32, u32) {
    let chars = text.chars().count() as u32;
    let w = chars * (CHAR_W + 1) * scale;
    let h = CHAR_H * scale;
    (w, h)
}

